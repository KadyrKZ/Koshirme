from datetime import UTC
from urllib.parse import urlsplit, urlunsplit

from fastapi import HTTPException
from sqlalchemy.ext.asyncio import AsyncSession

from app.database import lock_exam
from app.models import StudentSession, ViolationEvent, utcnow
from app.schemas.api import EventCreate, EventOut, StudentOut
from app.websockets.hub import hub

RULES = {
    "PAGE_HIDDEN": ("medium", 5),
    "NEW_TAB": ("medium", 10),
    "TAB_CHANGED": ("high", 20),
    "GOOGLE_LENS_ATTEMPT": ("high", 0),
    "BROWSER_UI_ATTEMPT": ("high", 15),
    "CHROME_FOCUS_LOST": ("high", 25),
    "DESKTOP_GUARD_DISCONNECTED": ("high", 30),
    "STUDENT_DISCONNECTED": ("high", 30),
    "STUDENT_RECONNECTED": ("info", 0),
    "TEACHER_SCREENSHOT": ("info", 0),
    "RETURN_TO_EXAM": ("info", 0),
}


def aware(value):
    return value.replace(tzinfo=value.tzinfo or UTC)


def sanitize_url(value: str | None) -> str | None:
    if not value:
        return None
    try:
        url = urlsplit(value)
        if url.scheme not in {"http", "https", "chrome", "about", "chrome-extension"}:
            return None
        host = url.hostname or ""
        port = f":{url.port}" if url.port else ""
        return urlunsplit((url.scheme, host + port, url.path, "", ""))[:2048]
    except ValueError:
        return None


def insert_event(
    db: AsyncSession,
    student: StudentSession,
    event_type: str,
    *,
    event_id=None,
    current_url=None,
    metadata=None,
) -> ViolationEvent:
    severity, points = RULES[event_type]
    details = dict(metadata or {})
    if severity == "high":
        details["capture_status"] = (
            "unavailable"
            if event_type in {"STUDENT_DISCONNECTED", "DESKTOP_GUARD_DISCONNECTED"}
            else "pending"
        )
    event = ViolationEvent(
        student_session_id=student.id,
        event_type=event_type,
        severity=severity,
        current_url=sanitize_url(current_url),
        details=details,
        timestamp=utcnow(),
    )
    if event_id:
        event.id = event_id
    db.add(event)
    student.risk_score = min(100, student.risk_score + points)
    student.violations_count += severity != "info"
    student.last_event = event_type
    return event


async def publish_event(student: StudentSession, event: ViolationEvent, kind="event_created"):
    await hub.admin_broadcast(
        student.exam_id,
        {
            "type": kind,
            "event": EventOut.model_validate(event).model_dump(mode="json"),
            "student": StudentOut.model_validate(student).model_dump(mode="json"),
        },
    )


async def create_event(db: AsyncSession, student: StudentSession, payload: EventCreate):
    exam = await lock_exam(db, student.exam_id)
    await db.refresh(student)
    if not exam or not exam.active or not student.active:
        raise HTTPException(409, "Monitoring stopped")
    if payload.event_type == "STUDENT_DISCONNECTED":
        raise HTTPException(422, "This event is generated by the server")
    if RULES[payload.event_type][0] != payload.severity:
        raise HTTPException(422, "Severity does not match event type")
    existing = await db.get(ViolationEvent, str(payload.id))
    if existing:
        if existing.student_session_id != student.id or existing.event_type != payload.event_type:
            raise HTTPException(409, "Event ID already used")
        return existing
    event = insert_event(
        db,
        student,
        payload.event_type,
        event_id=str(payload.id),
        current_url=payload.current_url,
        metadata=payload.metadata,
    )
    await db.commit()
    await publish_event(student, event)
    return event


async def capture_eligible(db: AsyncSession, event: ViolationEvent, student: StudentSession):
    exam = await lock_exam(db, student.exam_id)
    await db.refresh(student)
    await db.refresh(event)
    if not exam or not exam.active or not student.active:
        raise HTTPException(409, "Monitoring stopped")
    if event.event_type != "TEACHER_SCREENSHOT" and (
        event.severity != "high" or event.event_type in {"STUDENT_DISCONNECTED", "DESKTOP_GUARD_DISCONNECTED"}
    ):
        raise HTTPException(409, "This event does not permit screen capture")
    if (utcnow() - aware(event.timestamp)).total_seconds() > 30:
        raise HTTPException(409, "Capture window expired")
